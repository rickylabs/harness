// Canonical files own content; compatibility artifacts are generated and checked, never maintained twice.
import { mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const map = JSON.parse(readFileSync(resolve(root, 'method/path-map.json'), 'utf8'));
const marker = '<!-- Generated by scripts/method-compatibility.mjs. Do not edit. -->';

export function headingTargets(text) {
  const targets = [], seen = new Map();
  let fence = null;
  for (const line of text.split('\n')) {
    const open = /^\s{0,3}(`{3,}|~{3,})/.exec(line);
    if (fence !== null) {
      if (open && open[1][0] === fence[0] && open[1].length >= fence.length) fence = null;
      continue;
    }
    if (open) { fence = open[1]; continue; }
    const heading = /^\s{0,3}(#{1,6})\s+(.+?)\s*#*\s*$/.exec(line);
    if (!heading) continue;
    const base = heading[2].replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1').replace(/!?\[([^\]]*)\]\[[^\]]*\]/g, '$1')
      .trim().toLowerCase().replace(/[^\p{L}\p{N}\p{M}\p{Pc}\s-]/gu, '').replace(/\s/g, '-');
    if (!base) continue;
    const n = seen.get(base) ?? 0;
    seen.set(base, n + 1);
    targets.push({ title: heading[2], anchor: n === 0 ? base : `${base}-${n}` });
  }
  return targets;
}

export function compatibilityContent(entry, canonical) {
  const target = relative(dirname(resolve(root, entry.legacy)), resolve(root, entry.canonical)).split(sep).join('/');
  if (entry.kind === 'template') return canonical;
  if (entry.kind === 'document') {
    const targets = headingTargets(canonical);
    return `${marker}\n\n# Compatibility pointer\n\nThe canonical document is [${entry.canonical}](${target}).\nThis file retains navigation for the former path; edit the canonical document.\n\n` +
      targets.map(({ title, anchor }) => `<a id="${anchor}"></a>\n\nSee [${title.replace(/`/g, '')}](${target}#${anchor}).\n`).join('\n');
  }
  const exportAll = `export * from '${target}';\n`;
  if (entry.kind === 'module') return `// Generated by scripts/method-compatibility.mjs; edit ${entry.canonical}.\n${exportAll}`;
  if (entry.kind === 'test') return `// Generated by scripts/method-compatibility.mjs; edit ${entry.canonical}.\nimport '${target}';\n`;
  if (entry.kind === 'cli' && entry.legacy.endsWith('.ts'))
    return `// Generated by scripts/method-compatibility.mjs; edit ${entry.canonical}.\n${exportAll}import { main } from '${target}';\n\nif (import.meta.main) await main();\n`;
  if (entry.kind === 'cli' && entry.legacy.endsWith('.mjs'))
    return `// Generated by scripts/method-compatibility.mjs; edit ${entry.canonical}.\n${exportAll}import { isMain, main } from '${target}';\n\nif (isMain(import.meta.url)) main();\n`;
  throw new Error('unrecognized compatibility entry kind');
}

function main() {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== '--write')) throw new Error('usage: method-compatibility.mjs [--write]');
  if (map.schemaVersion !== 1 || map.entries.length !== 26) throw new Error('expected schema1 complete 26-entry path map');
  const stale = [];
  for (const entry of map.entries) {
    const canonical = readFileSync(resolve(root, entry.canonical), 'utf8');
    const output = compatibilityContent(entry, canonical);
    if (args[0] === '--write') {
      mkdirSync(dirname(resolve(root, entry.legacy)), { recursive: true });
      writeFileSync(resolve(root, entry.legacy), output);
    } else {
      let current;
      try { current = readFileSync(resolve(root, entry.legacy), 'utf8'); } catch { current = null; }
      if (current !== output) stale.push(entry.legacy);
    }
  }
  if (stale.length) {
    console.error(`method compatibility stale: ${stale.join(', ')}; regenerate with node scripts/method-compatibility.mjs --write`);
    process.exitCode = 1;
  } else console.log(`method compatibility: ${map.entries.length} entries ${args[0] === '--write' ? 'written' : 'current'}`);
}
if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) main();
